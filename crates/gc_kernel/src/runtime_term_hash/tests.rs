use super::*;
use gc_coreform::{hash_term, print_term};
use num_bigint::BigInt;
use std::collections::{BTreeMap, BTreeSet};

fn limits() -> RuntimeTermHashLimits {
    RuntimeTermHashLimits {
        max_nodes: 200_001,
        max_encoded_bytes: 2_000_000,
        max_pending_frames: 30_001,
    }
}
fn pair(car: i64, cdr: i64) -> Term {
    Term::Pair(
        Box::new(Term::Int(car.into())),
        Box::new(Term::Int(cdr.into())),
    )
}
fn hex(hash: [u8; 32]) -> String {
    hash.iter().map(|byte| format!("{byte:02x}")).collect()
}

