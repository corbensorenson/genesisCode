#[test]
fn structural_term_hash_separates_nested_improper_and_raw_symbol_aliases() {
    let mut terms = vec![
        Term::Nil,
        Term::Symbol("nil".into()),
        Term::Bool(true),
        Term::Symbol("true".into()),
        Term::Int(1.into()),
        Term::Symbol("1".into()),
        Term::Str("x".into()),
        Term::Symbol("x".into()),
        Term::Bytes(b"x".to_vec().into()),
        Term::list(vec![
            Term::Symbol("pair".into()),
            Term::Symbol("<improper>".into()),
        ]),
    ];
    for number in -16..16 {
        terms.push(pair(number, number + 1));
    }
    let mut hashes = BTreeMap::new();
    for term in terms {
        for nested in [
            term.clone(),
            Term::Vector(vec![term.clone()]),
            Term::Map([(TermOrdKey(Term::Nil), term.clone())].into()),
            Term::Map([(TermOrdKey(term), Term::Nil)].into()),
        ] {
            let hash = runtime_term_hash(&nested, limits()).unwrap();
            if let Some(previous) = hashes.insert(hash, nested.clone()) {
                assert_eq!(previous, nested, "unequal structural terms aliased");
            }
        }
    }
    assert_eq!(hashes.len(), 167);
}

#[test]
fn structural_term_hash_does_not_change_canonical_store_or_legacy_value_identity() {
    let proper = Term::list(vec![
        Term::Symbol("pair".into()),
        Term::Symbol("<improper>".into()),
    ]);
    assert_eq!(print_term(&proper), "(pair <improper>)");
    // A frozen existing v0.2 canonical hash; the additive profile cannot replace it.
    assert_eq!(
        hex(hash_term(&proper)),
        "59564e4d8fcafbd06c06a5f54deefc6969cdd72861eb7ee50da1fd5c9c4bc9c9"
    );
    assert_eq!(
        hex(crate::value_hash(&crate::Value::data(proper))),
        "b9ad37409e134445e770a816fd877728d009267997f0eb8fd926cd40e09ced02"
    );
    assert_eq!(
        crate::VALUE_EFFECT_HASH_PROFILE_ID,
        "genesis/value-effect-hash/v0.2"
    );
    assert_eq!(
        RUNTIME_TERM_HASH_PROFILE_ID,
        "genesis/runtime-term-hash/v0.3"
    );
}

#[test]
fn structural_term_hash_limits_are_exact_and_fail_with_typed_dimensions() {
    let term = Term::Vector(vec![Term::Bool(false), Term::Nil]);
    let bytes = DOMAIN.len() as u64 + 9 + 2 + 1;
    let exact = RuntimeTermHashLimits {
        max_nodes: 3,
        max_encoded_bytes: bytes,
        max_pending_frames: 2,
    };
    runtime_term_hash(&term, exact).unwrap();
    for (short, dimension, observed, limit) in [
        (
            RuntimeTermHashLimits {
                max_nodes: 2,
                ..exact
            },
            "runtime-hash-nodes",
            3,
            2,
        ),
        (
            RuntimeTermHashLimits {
                max_encoded_bytes: bytes - 1,
                ..exact
            },
            "runtime-hash-bytes",
            bytes,
            bytes - 1,
        ),
        (
            RuntimeTermHashLimits {
                max_pending_frames: 1,
                ..exact
            },
            "runtime-hash-frames",
            2,
            1,
        ),
        (
            RuntimeTermHashLimits {
                max_pending_frames: 0,
                ..exact
            },
            "runtime-hash-frames",
            1,
            0,
        ),
        (
            RuntimeTermHashLimits {
                max_nodes: 0,
                ..exact
            },
            "runtime-hash-nodes",
            1,
            0,
        ),
        (
            RuntimeTermHashLimits {
                max_encoded_bytes: 0,
                ..exact
            },
            "runtime-hash-bytes",
            DOMAIN.len() as u64,
            0,
        ),
    ] {
        let error = runtime_term_hash(&term, short).unwrap_err();
        assert!(matches!(error.kind, KernelErrorKind::MemoryLimit));
        assert_eq!(
            error.resource_limit.unwrap(),
            crate::ResourceLimit {
                dimension,
                observed,
                limit
            }
        );
    }
    let huge_integer = Term::Int(BigInt::from(1_u8) << 32768);
    let error = runtime_term_hash(
        &huge_integer,
        RuntimeTermHashLimits {
            max_encoded_bytes: DOMAIN.len() as u64 + 10,
            ..limits()
        },
    )
    .unwrap_err();
    assert_eq!(
        error.resource_limit.unwrap().dimension,
        "runtime-hash-bytes"
    );
    let huge_blob = Term::Bytes(vec![42; 1_000_000].into());
    let error = runtime_term_hash(
        &huge_blob,
        RuntimeTermHashLimits {
            max_encoded_bytes: DOMAIN.len() as u64 + 9,
            ..limits()
        },
    )
    .unwrap_err();
    assert_eq!(
        error.resource_limit.unwrap().observed,
        DOMAIN.len() as u64 + 9 + 1_000_000
    );
}

fn dismantle_pair(mut term: Term) {
    // Term's own destructor is a separate boundary; do not make it this hash test's stack limit.
    while let Term::Pair(car, cdr) = term {
        assert_eq!(*cdr, Term::Nil);
        term = *car;
    }
}

#[test]
fn structural_term_hash_streams_deep_and_wide_without_host_recursion_or_fanout_stack() {
    std::thread::Builder::new()
        .stack_size(96 * 1024)
        .spawn(|| {
            let mut term = Term::Nil;
            for _ in 0..20_000 {
                term = Term::Pair(Box::new(term), Box::new(Term::Nil));
            }
            let result = runtime_term_hash(&term, limits());
            let bounded = runtime_term_hash(
                &term,
                RuntimeTermHashLimits {
                    max_pending_frames: 16,
                    ..limits()
                },
            );
            dismantle_pair(term);
            result.unwrap();
            assert_eq!(
                bounded.unwrap_err().resource_limit.unwrap().dimension,
                "runtime-hash-frames"
            );
        })
        .unwrap()
        .join()
        .unwrap();
    let wide = Term::Vector(vec![Term::Nil; 100_000]);
    runtime_term_hash(
        &wide,
        RuntimeTermHashLimits {
            max_pending_frames: 2,
            ..limits()
        },
    )
    .unwrap();
    let map = Term::Map(
        (0..10_000)
            .map(|n| (TermOrdKey(Term::Int(n.into())), Term::Nil))
            .collect(),
    );
    runtime_term_hash(
        &map,
        RuntimeTermHashLimits {
            max_pending_frames: 3,
            ..limits()
        },
    )
    .unwrap();
}

#[test]
fn structural_term_hash_map_identity_preserves_canonical_key_order() {
    let forward: BTreeMap<_, _> = (0..64)
        .map(|n| (TermOrdKey(pair(n, n + 1)), Term::Str(n.to_string())))
        .collect();
    let backward: BTreeMap<_, _> = (0..64)
        .rev()
        .map(|n| (TermOrdKey(pair(n, n + 1)), Term::Str(n.to_string())))
        .collect();
    assert_eq!(
        runtime_term_hash(&Term::Map(forward), limits()).unwrap(),
        runtime_term_hash(&Term::Map(backward), limits()).unwrap()
    );
}

#[test]
fn structural_term_hash_counter_overflow_is_an_explicit_error_at_maximum_limits() {
    let mut encoder = Encoder {
        hasher: Hasher::new(),
        limits: RuntimeTermHashLimits {
            max_nodes: u64::MAX,
            max_encoded_bytes: u64::MAX,
            max_pending_frames: usize::MAX,
        },
        nodes: u64::MAX,
        bytes: u64::MAX,
    };
    for error in [
        encoder.node().unwrap_err(),
        encoder.charge_bytes(1).unwrap_err(),
    ] {
        assert!(matches!(error.kind, KernelErrorKind::MemoryLimit));
        assert!(
            error.resource_limit.is_none(),
            "overflow has no representable exact observation"
        );
    }
}
